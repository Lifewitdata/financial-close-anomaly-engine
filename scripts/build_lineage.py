"""
Generate the lineage graph from the dbt artefacts, not from a hand-drawn picture.

Reads target/manifest.json (written by `dbt docs generate` / `dbt build`) and emits:

  LINEAGE.md       mermaid DAG, rendered natively by GitHub, + the node inventory
  README snippet   the same diagram is referenced from README.md, never retyped

Because it is generated from the manifest, the committed diagram cannot drift from the
models that actually exist - which is the usual way a portfolio lineage picture rots.

Run:  python scripts/build_lineage.py   (after dbt docs generate)
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "target" / "manifest.json"
OUT = ROOT / "LINEAGE.md"

LAYERS = [
    ("Raw     / ERP feed (seeds)", "raw"),
    ("Bronze  / staging", "staging"),
    ("Silver  / intermediate", "silver"),
    ("Gold    / marts", "gold"),
    ("Gold    / SCD2 history", "scd2"),
]


def layer_of(node):
    path = (node.get("path") or "").replace("\\", "/")
    if node["resource_type"] == "seed":
        return "raw"
    if node["resource_type"] == "snapshot":
        return "scd2"
    if "staging/" in path:
        return "staging"
    if "intermediate/" in path:
        return "silver"
    if "marts/" in path:
        return "gold"
    return "other"


def main():
    if not MANIFEST.exists():
        print(f"missing {MANIFEST} - run `dbt docs generate --profiles-dir .` first")
        return 1

    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    nodes = {k: v for k, v in manifest["nodes"].items() if v["resource_type"] in ("model", "seed", "snapshot")}
    sources = {k: v for k, v in manifest["sources"].items()}

    edges = []
    for key, node in nodes.items():
        for parent in manifest["parent_map"].get(key, []):
            if parent in nodes:
                edges.append((nodes[parent]["name"], node["name"]))
            elif parent in sources:
                edges.append((sources[parent]["name"] + " (source)", node["name"]))

    lines = [
        "# Lineage",
        "",
        "Generated by `python scripts/build_lineage.py` from `target/manifest.json`, so this",
        "graph is the graph dbt built - it cannot drift from the models that exist.",
        "",
        "```mermaid",
        "flowchart LR",
    ]

    emitted = set()
    for _, layer_key in LAYERS:
        members = [n for n in nodes.values() if layer_of(n) == layer_key]
        if not members:
            continue
        title = next(t for t, k in LAYERS if k == layer_key)
        lines.append(f"    subgraph {layer_key.replace('  ', '_')}[\"{title}\"]")
        lines.append("        direction TB")
        for node in sorted(members, key=lambda n: n["name"]):
            shape = "(" + node["name"] + ")" if node["resource_type"] == "seed" else "[" + node["name"] + "]"
            lines.append(f"        {node['name']}{shape}")
            emitted.add(node["name"])
        lines.append("    end")

    for src, dst in sorted(set(edges)):
        src_id = src.replace(" (source)", "_src")
        lines.append(f"    {src_id} --> {dst}")

    lines += [
        "```",
        "",
        "## Node inventory",
        "",
        "| Node | Layer | Materialisation | Schema | Column tests |",
        "|---|---|---|---|---|",
    ]
    for key in sorted(nodes, key=lambda k: (layer_of(nodes[k]), nodes[k]["name"])):
        node = nodes[key]
        schema = node["schema"]
        materialised = node["config"]["materialized"]
        tested = sum(
            1
            for t in manifest["nodes"].values()
            if t["resource_type"] == "test" and key in manifest["parent_map"].get(t["unique_id"], [])
        )
        lines.append(
            f"| `{node['name']}` | {layer_of(node)} | {materialised} | `{schema}` | {tested} |"
        )

    lines += [
        "",
        "## Controls as tested assertions",
        "",
        "| Test | Kind | Severity | What failing means |",
        "|---|---|---|---|",
        "| `assert_debits_equals_credits` | custom | warn | A journal does not balance - FC-01 break |",
        "| `assert_no_orphan_accounts` | custom | warn | A line references an account outside the chart - FC-02 |",
        "| `assert_no_negative_amounts` | custom | warn | Sign convention broken in the extract |",
        "| `assert_no_missing_fx_rate` | custom | error | USD figures would be silently wrong - FC-05 |",
        "| `unique_current_version` | generic | error | SCD2 history has two live versions of one cost centre |",
        "",
        "The warn-severity tests are configured to warn on purpose: during a close they are the",
        "exception report Finance works from, and `fct_monthly_close_summary.close_status` is the",
        "gate that blocks sign-off while rows remain.",
        "",
    ]

    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.name}: {len(nodes)} nodes, {len(set(edges))} edges, {len(sources)} declared sources")
    return 0


if __name__ == "__main__":
    sys.exit(main())
